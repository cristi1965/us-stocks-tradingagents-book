const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless:true, channel: 'chrome'});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto(process.env.LEARNING_URL || 'http://127.0.0.1:4186');
  await page.waitForFunction(()=>window.LearningPractice?.lessons.length>28);
  const lessons=await page.evaluate(()=>window.LEARNING_LESSONS);
  assert.equal(lessons.length,28); assert.equal(new Set(lessons.map(l=>l.id)).size,28);
  await page.locator('#learnNav').click();
  await page.locator('input[name=answer]').nth(1).check();
  await page.locator('#quiz button[type=submit]').click();
  assert.equal(await page.locator('#reviewCount').textContent(),'1');
  assert.match(await page.locator('#feedback').textContent(),/已加入复习/);
  await page.locator('#reviewNav').click();
  assert.equal(await page.locator('.review-item').count(),1);
  await page.locator('.review-item button[data-id]').click();
  await page.locator('input[name=answer]').nth(0).check();
  await page.locator('#quiz button[type=submit]').click();
  assert.equal(await page.locator('#reviewCount').textContent(),'0');
  await page.locator('.notes summary').click();
  await page.locator('#note').fill('我自己的复盘');
  await page.reload();
  await page.locator('#learnNav').click();
  assert.equal(await page.locator('#note').inputValue(),'我自己的复盘');
  assert.match(await page.locator('#progress').textContent(),/^1 \/ 28/);
  await page.locator('#search').fill('xyz-no-result');
  assert.match(await page.locator('#catalog').textContent(),/没有找到/);
  await page.locator('#search').fill('');
  for (const lesson of lessons) {
    await page.locator(`#catalog [data-id="${lesson.id}"]`).click();
    assert.equal(await page.locator('h1').textContent(),lesson.title);
    assert.equal(await page.locator('.dialogue-line').count(),3);
    assert.equal(await page.locator('.dialogue-line.coach p').textContent(),lesson.dialogue.answer);
    assert.equal(await page.locator('.self-check').getAttribute('open'),null);
    await page.locator('.self-check summary').click();
    assert.equal(await page.locator('.self-check p').textContent(),lesson.dialogue.checkAnswer);
    await page.locator('.terms summary').click();
    assert.equal(await page.locator('.terms dt').count(),lesson.terms.length);
    await page.locator('input[name=answer]').nth(lesson.quiz.answer).check();
    await page.locator('#quiz button[type=submit]').click();
    assert.match(await page.locator('#feedback').textContent(),/答对了/);
  }
  assert.match(await page.locator('#progress').textContent(),/^28 \/ 28/);
  await page.reload();
  assert.equal(await page.locator('h1').textContent(),lessons[27].title);
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#export').click();
  const download=await downloadPromise;
  assert.equal(download.suggestedFilename(),'tradingagents-learning.json');
  await page.locator(`#catalog [data-id="${lessons[0].id}"]`).click();
  fs.mkdirSync('output/playwright',{recursive:true});
  await page.screenshot({path:'output/playwright/learning-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.reload();
  await page.locator('#learnNav').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'output/playwright/learning-mobile.png',fullPage:true});
  await page.locator('#reviewNav').click();
  assert.match(await page.locator('#lesson').textContent(),/目前没有待复习/);
  const corrupt=await browser.newContext();
  await corrupt.addInitScript(()=>localStorage.setItem('tradingagents-learning-v1','{bad json'));
  const other=await corrupt.newPage(); await other.goto(process.env.LEARNING_URL || 'http://127.0.0.1:4186');
  assert.match(await other.locator('h1').textContent(),/不用先刷118篇文章/);
  await other.locator('#learnNav').click();
  assert.equal(await other.locator('h1').textContent(),lessons[0].title);
  assert.deepEqual(errors,[]);
  console.log('PASS: 28 lessons, answer feedback, review queue, notes, persistence, search, export, mobile overflow, corrupt storage, no runtime errors.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
