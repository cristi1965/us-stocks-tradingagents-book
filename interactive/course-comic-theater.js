(function() {
  function renderComicTheater() {
    const curChapter = (typeof window !== 'undefined' && window.v2Active !== undefined)
      ? window.v2Active
      : (typeof v2Active !== 'undefined' ? v2Active : +(localStorage.getItem('manga-us-v2-active') || 0));

    const phase2 = document.getElementById('lesson-phase-2');
    if (!phase2) return;
    const content = phase2.querySelector('.phase-content');
    if (!content) return;

    let theater = content.querySelector('.comic-theater-card');
    if (!theater) {
      theater = document.createElement('div');
      theater.className = 'comic-theater-card';
      // Insert after .story-thread or before .chapter-example
      const example = content.querySelector('.chapter-example');
      if (example) {
        example.before(theater);
      } else {
        content.appendChild(theater);
      }
    }

    const banter = window.COMIC_CHAPTER_BANTER[curChapter] || [
      ['chenpingan', '最后一章，把账户、订单、重大消息和退出计划从头检查一遍。'],
      ['libaoping', '遇到拆股或分红，先查正式通知，再核对股数、价格和未成交订单。'],
      ['ningyao', '资料不够就先停下。留下完整记录，才方便回头查哪里需要改。']
    ];
    const rowsHtml = banter.map(item => {
      const [speakerKey, text] = item;
      const char = window.COMIC_THEATER_ROSTER[speakerKey] || window.COMIC_THEATER_ROSTER.chenpingan;
      return '<div class="theater-bubble-row ' + char.class + '">' +
        '<img class="theater-avatar" src="' + char.avatar + '" alt="' + char.name + '">' +
        '<div class="theater-bubble">' +
          '<div class="theater-bubble-head">' +
            '<span class="theater-speaker-name">' + char.name + '</span>' +
            '<span class="theater-speaker-tag">' + char.tag + '</span>' +
          '</div>' +
          '<p>' + text + '</p>' +
        '</div>' +
      '</div>';
    }).join('');

    theater.innerHTML = 
      '<div class="theater-header">' +
        '<div class="theater-title-box">' +
          '<span class="theater-badge">⚡ 大家一起讨论</span>' +
          '<span class="theater-subtitle">虚构情景对白 · 第 ' + (curChapter + 1) + ' 章</span>' +
        '</div>' +
        '<span class="theater-tag">用故事理解本章规则</span>' +
      '</div>' +
      '<div class="theater-dialogue-list">' +
        rowsHtml +
      '</div>';
  }

  // Hook into v2Render safely
  const originalRender = window.v2Render;
  if (typeof originalRender === 'function') {
    window.v2Render = function() {
      originalRender.apply(this, arguments);
      renderComicTheater();
    };
  }

  // Also hook phase clicks
  document.addEventListener('click', function(e) {
    const btn = e.target.closest('[data-phase]');
    if (btn && btn.dataset.phase === '2') {
      setTimeout(renderComicTheater, 20);
    }
  });

  window.renderComicTheater = renderComicTheater;
  setTimeout(renderComicTheater, 50);
})();
